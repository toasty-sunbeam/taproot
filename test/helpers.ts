export { __test, makeEnv };

type Handler = (params: unknown, env: unknown) => Promise<string>;

export async function call(handler: Handler, env: unknown, params: unknown = {}) {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  return JSON.parse(await handler(params, env)) as any;
}

let seq = 0;
export function makeMemory(overrides: Partial<Memory> = {}): Memory {
  seq++;
  const ts = overrides.updated_at ?? `2026-10-${String((seq % 28) + 1).padStart(2, "0")}T12:00:00.000Z`;
  return {
    id: overrides.id ?? `00000000-0000-4000-8000-${String(seq).padStart(12, "0")}`,
    category: "active_thread",
    content: `Content for memory ${seq}. It has some words in it.`,
    salience: "medium",
    created_at: ts,
    updated_at: ts,
    source: { type: "direct_observation" },
    compression_level: 0,
    linked_memories: [],
    tags: [],
    search_keywords: [],
    gist: `Gist ${seq}`,
    gist_autogenerated: false,
    core: false,
    last_retrieved: null,
    retrieval_count: 0,
    epistemic_status: "unvalidated",
    replication_count: 0,
    provenance: null,
    ...overrides,
  };
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export async function seed(env: any, overrides: Partial<Memory> = {}): Promise<Memory> {
  const m = makeMemory(overrides);
  await putMemory(env.TAPROOT_KV, m);
  return m;
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export async function rawRecord(env: any, id: string): Promise<Record<string, unknown>> {
  return JSON.parse((await env.TAPROOT_KV.get(`mem:${id}`)) as string);
}
